#!/usr/bin/env python3
"""Writes the licence notices the program carries, from what Cargo.lock actually builds.

usage: packaging/notices.py [--check]   (--check fails if the file is out of date)
"""
import glob
import json
import os
import subprocess
import sys

OUT = "crates/linecon/assets/NOTICES.txt"
HEADER = """linecon0 is MIT licensed. See `linecon --licenses` for its own licence and PuTTY's.
This file lists everything else built into it. Generated by packaging/notices.py.

Fonts
-----
Inter and JetBrains Mono are embedded under the SIL Open Font License 1.1.

"""


def licence_files(directory):
    found = []
    for pattern in ("LICEN[CS]E*", "COPYING*", "NOTICE*", "UNLICENSE*"):
        found += glob.glob(os.path.join(glob.escape(directory), pattern))
    return sorted(path for path in set(found) if os.path.isfile(path))


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read().replace("\r\n", "\n").strip()


def build():
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--locked", "--format-version", "1"], text=True
        )
    )
    own = set(meta["workspace_members"])
    texts = {}
    no_file = []
    for package in sorted(meta["packages"], key=lambda p: (p["name"], p["version"])):
        if package["id"] in own:
            continue
        label = f'{package["name"]} {package["version"]} ({package.get("license") or "see below"})'
        files = licence_files(os.path.dirname(package["manifest_path"]))
        if not files:
            no_file.append(label)
        for path in files:
            texts.setdefault(read(path), []).append(label)
    parts = [HEADER]
    for name in ("Inter-OFL.txt", "JetBrainsMono-OFL.txt"):
        parts.append(read(os.path.join("crates/linecon/assets/fonts", name)) + "\n\n")
    if no_file:
        parts.append("Crates\n------\nThese state their licence in their metadata:\n")
        parts.extend(f"  {label}\n" for label in no_file)
        parts.append("\n")
    for text, labels in sorted(texts.items(), key=lambda item: item[1][0]):
        parts.append("=" * 72 + "\n")
        parts.extend(f"{label}\n" for label in sorted(set(labels)))
        parts.append("\n" + text + "\n\n")
    return "".join(parts)


def main():
    notices = build()
    if "--check" in sys.argv:
        current = read(OUT) if os.path.exists(OUT) else ""
        if current != notices.strip():
            sys.exit(f"{OUT} is out of date: run packaging/notices.py")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(notices.strip() + "\n")
    print(f"{OUT}: {len(notices) // 1024} KiB")


if __name__ == "__main__":
    main()
